function statusForVariance(variance: number): PlatformWbsStatus {
  if (variance >= 5) return "ahead";
  if (variance >= -2) return "on-track";
  if (variance > -5) return "at-risk";
  return "delayed";
}

const members = memberSeeds.map((member) => {
  const scheduleVariance = member.actualProgress - member.plannedProgress;
  return {
    ...member,
    scheduleVariance,
    status: statusForVariance(scheduleVariance),
  };
});

const plannedTaskCount = members.reduce((sum, member) => sum + member.plannedTaskCount, 0);
const completedTaskCount = members.reduce((sum, member) => sum + member.completedTaskCount, 0);

